/* spec.h - especificacao viva do agente, impressa por `delta docs` e `/docs`.
 *
 * Fonte unica: se o comportamento mudar, muda aqui (e a suite [26] quebra se
 * a spec citar algo que o binario nao tem).
 */
#ifndef DELTA_SPEC_H
#define DELTA_SPEC_H

static const char DELTA_SPEC[] =
    "DELTA AGENT - especificacao\n"
    "\n"
    "1. Loop do turno\n"
    "   prompt -> provedor (streaming) -> tool calls -> resultados -> proximo passo,\n"
    "   ate o modelo responder sem ferramenta. O Delta e' dono do loop e das\n"
    "   ferramentas; o modelo so' pede.\n"
    "   Tetos: 200 passos (DELTA_MAX_STEPS), 200 KB por saida de ferramenta,\n"
    "   8 MB de contexto por request (poda de emergencia em 4 saidas/20 KB).\n"
    "   Turno vazio do provedor (200 sem texto e sem tool call) e' retentado ate\n"
    "   6 vezes com um empurrao explicito; depois falha com erro (nunca silencio).\n"
    "\n"
    "2. Ferramentas\n"
    "   read write edit undo bash ls find grep graph fs shell git web memory code\n"
    "   assert agent extend skills mcp extensions. Familias unificadas usam \"op\".\n"
    "   Toda escrita guarda snapshot de undo. tools_exec tem teto de 200 KB e mata\n"
    "   o filho ao estourar; ESC/Ctrl+C mata o filho em curso (codigo 130).\n"
    "\n"
    "3. Sessao\n"
    "   ~/.deltaCore/sessions/--<slug-da-pasta>--/<data>_<id>.jsonl\n"
    "   JSONL v3: {\"type\":\"session\",...} + {\"type\":\"message\",\"message\":{...}}.\n"
    "   `delta continue` retoma a ultima; `delta export [--json]` traduz a sessao\n"
    "   para markdown (ou NDJSON) no stdout.\n"
    "\n"
    "4. Superficie para CI\n"
    "   `delta -p \"<prompt>\" --json` emite NDJSON, um evento por linha:\n"
    "   text, thinking, tool_call, tool_result, turn_end, error.\n"
    "   Codigo de saida: 0 ok, 1 erro do agente, 124 timeout de comando.\n"
    "\n"
    "5. Extensoes (manifesto unificado)\n"
    "   ~/.deltaCore/extensions.json e' uma lista; cada item pode trazer:\n"
    "     name, enabled, desc\n"
    "     prompt   texto anexado ao system prompt\n"
    "     tools    [{name,arg,desc,schema}]\n"
    "     commands [{name,arg(prompt),exec,desc}]\n"
    "     hooks    [{event,arg,desc}]\n"
    "     ui       {\"status\": \"comando\"} -> terceira linha do rodape\n"
    "   Formato antigo (kind=tool|skill|command|mcp|hook) continua valido.\n"
    "   O agente cria com a tool `extensions` (op=add ou op=bundle).\n"
    "\n"
    "6. Eventos do harness\n"
    "   tool_call    antes da ferramenta. Resposta: {\"block\":true,\"reason\":...}\n"
    "                ou {\"args\":\"<json>\"} para reescrever.\n"
    "   tool_result  depois. Resposta: {\"output\":...} ou {\"append\":...}.\n"
    "   user_message antes do request. Pode recusar com block.\n"
    "   turn_start   antes de cada chamada ao provedor.\n"
    "   turn_end     fim do turno (resposta ignorada).\n"
    "   session_start uma vez por processo.\n"
    "   Protocolo: payload JSON num arquivo, caminho em argv[1]; resposta JSON no\n"
    "   stdout; teto de 5 s e 8 KB; fail-open (hook quebrado nao para o agente).\n"
    "   Caminho com espaco precisa de aspas dentro do arg.\n"
    "\n"
    "7. Configuracao e dados\n"
    "   ~/.deltaCore/: config.json auth.json models.v2.json memory.json sessions/\n"
    "   skills/ mcps/ extensions/ graphs/ hooks/ system/prompt.md themes/ undo/\n"
    "   system/prompt.md e' relido a cada turno. Tudo gravado com escrita atomica.\n"
    "\n"
    "8. Limites conhecidos\n"
    "   macOS: so' fonte, sem binario pronto. Linux: desktop nao exercitado.\n"
    "   Sem sandbox de sistema: hooks e extensoes rodam com as mesmas permissoes\n"
    "   do Delta. UI nao e' extensivel (sem plugin in-process).\n"
    "\n"
    "Site: https://descz.github.io/delta/   Codigo: https://github.com/descz/delta\n";

#endif /* DELTA_SPEC_H */
